"""Generate the C shim and the I/O map for the function block.

Reads the VAR_INPUT / VAR_OUTPUT declarations of the FUNCTION_BLOCK
from the ST source and writes:

  build/plc/shim.c      flat C structs + rt_init / rt_scan around the
                        matiec-generated function block
  build/plc/io_map.json field names and types, used by the Python ctypes wrapper to
                        build matching ctypes structures

Usage: python plc/gen_shim.py <source.st> <out_dir> <FB_NAME>
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

FB_NAME = "ROUTINE_TEST"   # replaced by the third argument

# IEC type -> (C type used in the flat structs, ctypes name)
TYPES = {
    "REAL": ("float", "c_float"),
    "INT": ("int16_t", "c_int16"),
    "BOOL": ("uint8_t", "c_uint8"),
    "DWORD": ("uint32_t", "c_uint32"),
}


def strip_comments(text: str) -> str:
    return re.sub(r"\(\*.*?\*\)", "", text, flags=re.S)


def parse_section(body: str, section: str) -> list[tuple[str, str]]:
    m = re.search(rf"\b{section}\b(.*?)\bEND_VAR\b", body, flags=re.S | re.I)
    if not m:
        raise SystemExit(f"{section} not found in {FB_NAME}")
    fields: list[tuple[str, str]] = []
    for decl in m.group(1).split(";"):
        decl = decl.strip()
        if not decl:
            continue
        names, _, typ = decl.partition(":")
        typ = typ.split(":=")[0].strip().upper()
        if typ not in TYPES:
            raise SystemExit(f"unsupported type {typ!r} in {section}: {decl!r}")
        for name in names.split(","):
            fields.append((name.strip().upper(), typ))
    return fields


def parse_constants(body: str) -> dict[str, int]:
    m = re.search(r"\bVAR\s+CONSTANT\b(.*?)\bEND_VAR\b", body, flags=re.S | re.I)
    consts: dict[str, int] = {}
    if m:
        for name, value in re.findall(r"(\w+)\s*:\s*INT\s*:=\s*(-?\d+)\s*;", m.group(1)):
            consts[name.upper()] = int(value)
    return consts


def main() -> None:
    global FB_NAME
    if len(sys.argv) > 3:
        FB_NAME = sys.argv[3]
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    text = strip_comments(src.read_text(encoding="utf-8"))
    m = re.search(rf"FUNCTION_BLOCK\s+{FB_NAME}\b(.*?)END_FUNCTION_BLOCK", text, flags=re.S)
    if not m:
        raise SystemExit(f"FUNCTION_BLOCK {FB_NAME} not found")
    body = m.group(1)
    inputs = parse_section(body, "VAR_INPUT")
    outputs = parse_section(body, "VAR_OUTPUT")
    consts = parse_constants(body)

    def struct(name: str, fields: list[tuple[str, str]]) -> str:
        lines = [f"typedef struct {{"]
        lines += [f"  {TYPES[t][0]} {n};" for n, t in fields]
        lines.append(f"}} {name};")
        return "\n".join(lines)

    set_in = "\n".join(f"  __SET_VAR(fb.,{n},,in->{n});" for n, _ in inputs)
    get_out = "\n".join(f"  out->{n} = __GET_VAR(fb.{n},);" for n, _ in outputs)

    shim = f"""/* Generated by plc/gen_shim.py from {src.name}. Do not edit. */
#include <stdint.h>
#include "iec_std_lib.h"
#include "accessor.h"
#include "POUS.h"
#define GLOBAL_CAST static
#include "POUS.c"

/* used by the standard timer function blocks in iec_std_FB.h */
TIME __CURRENT_TIME;

/* matiec routes the IEC math functions (EXP, LN, ...) to these runtime hooks; a PLC runtime would
   provide them, here libm does. */
#include <math.h>
double iec_lib_exp(double x) {{ return exp(x); }}
double iec_lib_log(double x) {{ return log(x); }}
double iec_lib_log10(double x) {{ return log10(x); }}
double iec_lib_sqrt(double x) {{ return sqrt(x); }}
double iec_lib_pow(double x, double y) {{ return pow(x, y); }}

{struct("rt_in_t", inputs)}

{struct("rt_out_t", outputs)}

static {FB_NAME}_data__ fb;

void rt_init(void) {{
  {FB_NAME}_init__(&fb, 0);
}}

void rt_scan(const rt_in_t *in, rt_out_t *out) {{
{set_in}
  {FB_NAME}_body__(&fb);
{get_out}
}}

int rt_sizeof_in(void) {{ return (int)sizeof(rt_in_t); }}
int rt_sizeof_out(void) {{ return (int)sizeof(rt_out_t); }}
"""
    (out / "shim.c").write_text(shim, encoding="utf-8")
    io_map = {
        "inputs": [[n, TYPES[t][1]] for n, t in inputs],
        "outputs": [[n, TYPES[t][1]] for n, t in outputs],
        "constants": consts,
    }
    (out / "io_map.json").write_text(json.dumps(io_map, indent=1), encoding="utf-8")
    print(f"{len(inputs)} inputs, {len(outputs)} outputs, {len(consts)} constants")


if __name__ == "__main__":
    main()
