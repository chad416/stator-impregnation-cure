"""Generate a Siemens TIA Portal SCL external source from an ST source file.

The ST source stays the single source of truth. This converts it to the
SCL dialect that TIA Portal imports as an external source file:

  * local names (inputs, outputs, statics, constants) get the '#' prefix
  * user FC calls are quoted: "ARRH"(tC := ...)
  * MAX / MIN / LIMIT / SHL use formal parameters (IN1/IN2, MN/IN/MX, IN/N)
  * DWORD#n literals become DW#16#n (hex)
  * block headers get TIA attributes

Usage: python plc/st_to_scl.py <source.st> <target.scl>

Not compiled here: TIA Portal is not part of CI. Import it with
"External source files > Add new external file", then "Generate blocks
from source".
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

TOKEN = re.compile(r"\(\*.*?\*\)|'[^']*'|[A-Za-z_]\w*#[\w.#]+|[A-Za-z_]\w*|\d+\.\d+(?:[eE][-+]?\d+)?|\d+|:=|<>|<=|>=|\s+|.", re.S)
FORMAL = {"MAX": ["IN1", "IN2"], "MIN": ["IN1", "IN2"], "LIMIT": ["MN", "IN", "MX"], "SHL": ["IN", "N"]}
FC_FORMAL: dict[str, list[str]] = {}   # user functions are called with formal parameters in the ST source already
USER_FUNCS: set[str] = set()


def tokens(text: str) -> list[str]:
    return TOKEN.findall(text)


def declared_names(decl: str) -> set[str]:
    names = set()
    for sec in re.findall(r"\bVAR(?:_INPUT|_OUTPUT|_IN_OUT)?(?:\s+CONSTANT)?\b(.*?)\bEND_VAR\b", decl, flags=re.S):
        sec = re.sub(r"\(\*.*?\*\)", "", sec, flags=re.S)
        for d in sec.split(";"):
            if ":" in d:
                for n in d.split(":")[0].split(","):
                    if n.strip():
                        names.add(n.strip().upper())
    return names


def split_args(toks: list[str], i: int) -> tuple[list[list[str]], int]:
    """toks[i] == '('. Returns the top-level arguments and the index after ')'."""
    depth, args, cur = 0, [], []
    j = i
    while True:
        t = toks[j]
        if t == "(":
            depth += 1
            if depth > 1:
                cur.append(t)
        elif t == ")":
            depth -= 1
            if depth == 0:
                args.append(cur)
                return args, j + 1
            cur.append(t)
        elif t == "," and depth == 1:
            args.append(cur)
            cur = []
        else:
            cur.append(t)
        j += 1


def convert_body(toks: list[str], names: set[str]) -> str:
    out: list[str] = []
    i = 0
    prev_sig = ""
    while i < len(toks):
        t = toks[i]
        up = t.upper()
        nxt = next((k for k in range(i + 1, len(toks)) if not toks[k].isspace()), None)
        is_call = nxt is not None and toks[nxt] == "("
        if up in FORMAL and is_call and prev_sig != ".":
            args, end = split_args(toks, nxt)
            if len(args) == len(FORMAL[up]) and not any(":=" in a for a in args):
                parts = [f"{p} := {convert_body(a, names).strip()}" for p, a in zip(FORMAL[up], args)]
                out.append(f"{up}({', '.join(parts)})")
                i, prev_sig = end, ")"
                continue
        if up in FC_FORMAL and is_call:
            args, end = split_args(toks, nxt)
            parts = [f"{p} := {convert_body(a, names).strip()}" for p, a in zip(FC_FORMAL[up], args)]
            out.append(f'"{up}"({", ".join(parts)})')
            i, prev_sig = end, ")"
            continue
        if up in USER_FUNCS and is_call:
            out.append(f'"{t}"')
            i, prev_sig = i + 1, t
            continue
        m = re.fullmatch(r"DWORD#(\d+)", t, flags=re.I)
        if m:
            out.append(f"DW#16#{int(m.group(1)):X}")
        elif up in names and prev_sig != ".":
            out.append("#" + t)
        else:
            out.append(t)
        if not t.isspace() and not t.startswith("(*"):
            prev_sig = t
        i += 1
    return "".join(out)


def convert(src: str) -> str:
    USER_FUNCS.update(n.upper() for n in re.findall(r"\bFUNCTION\s+(\w+)\s*:", src))
    blocks = re.findall(r"(FUNCTION_BLOCK|FUNCTION)\s+(\w+)(.*?)\b(END_FUNCTION_BLOCK|END_FUNCTION)\b", src, flags=re.S)
    header = re.match(r"\s*(\(\*.*?\*\))", src, flags=re.S)
    parts = []
    parts.append("(* Generated by plc/st_to_scl.py from the ST source in plc/st. Do not edit:\n"
                 "   change the ST source and regenerate. Not compiled in CI (no TIA Portal there).\n"
                 "   Import in TIA Portal: External source files > Add new external file >\n"
                 "   Generate blocks from source. *)")
    if header:
        parts.append(header.group(1).strip())
    for kind, name, body, end in blocks:
        m = re.search(r"\bEND_VAR\b(?!.*\bEND_VAR\b)", body, flags=re.S)
        decl, code = body[: m.end()], body[m.end():]
        names = declared_names(decl)
        decl = decl.replace("DWORD#", "DW#16#")
        if kind == "FUNCTION":
            ret = re.match(r"\s*:\s*(\w+)", decl)
            rest = decl[ret.end():]
            names.add(name.upper())
            head = f'FUNCTION "{name}" : {ret.group(1)}\n{{ S7_Optimized_Access := \'TRUE\' }}\nVERSION : 0.1'
            parts.append(f"{head}{rest}\nBEGIN{convert_body(tokens(code), names)}\n{end}")
        else:
            head = f'FUNCTION_BLOCK "{name}"\n{{ S7_Optimized_Access := \'TRUE\' }}\nVERSION : 0.1'
            parts.append(f"{head}{decl}\n\nBEGIN{convert_body(tokens(code), names)}\n{end}")
    return "\n\n".join(parts) + "\n"


def main() -> None:
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(convert(src), encoding="utf-8", newline="\r\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
